// Generates `app/styles/radix-system-dark.css`.
//
// Why this exists:
// Radix ships dark values scoped to `.dark, .dark-theme`. Our `<html>` can also
// carry the class `system`, meaning "follow the OS". That class matches neither
// `.light` nor `.dark`, so under `prefers-color-scheme: dark` a `system` user
// would otherwise get the light palette. This file re-declares Radix's dark
// values under `.system` inside `@media (prefers-color-scheme: dark)`.
//
// The output is a STATIC, committed file (no build-time dependency). Re-run this
// only when bumping @radix-ui/colors:  node scripts/generate-system-dark-css.mjs
//
// Transform: take each dark scale as-is, swap the selector `.dark, .dark-theme`
// -> `.system`, then wrap everything in the prefers-dark media query. The nested
// @supports/@media (p3) block is carried through unchanged (valid nested CSS,
// handled by Lightning CSS in Tailwind 4).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");

// Every scale `app/app.css` imports, in the same order. Keep the two in sync.
const SCALES = ["mauve"];

function darkFileFor(scale) {
  // Resolve through the package so pnpm's nested layout is handled for us.
  return require.resolve(`@radix-ui/colors/${scale}-dark.css`);
}

const bodies = SCALES.map((scale) => {
  const css = readFileSync(darkFileFor(scale), "utf8").trim();
  // `.dark, .dark-theme` -> `.system`, everywhere it appears (base + p3 blocks).
  const rescoped = css.replaceAll(".dark, .dark-theme", ".system");
  // Indent one level so it reads well inside the wrapping media query.
  const indented = rescoped
    .split("\n")
    .map((line) => (line.length ? `  ${line}` : line))
    .join("\n");
  return `  /* ${scale} */\n${indented}`;
}).join("\n\n");

const output = `/* GENERATED by scripts/generate-system-dark-css.mjs — do not edit by hand. */
/* Re-run after bumping @radix-ui/colors. See the script for the why. */

@media (prefers-color-scheme: dark) {
${bodies}
}
`;

const outPath = resolve(repoRoot, "app/styles/radix-system-dark.css");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${outPath}`);
